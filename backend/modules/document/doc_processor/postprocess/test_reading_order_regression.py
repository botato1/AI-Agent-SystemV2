"""reading_order.py 회귀 테스트.

v1은 "블록 중심이 좌/우 중 어디에 있는가"만 보고 2단 컬럼을 판단해서
표(3열 이상)나 단일 컬럼 문서까지 오탐 → 21건 eval에서 CER 10.00%→14.12%로
악화되는 회귀를 냈다 (bok_payment_report_p101: 99.68%→40.31% 등).

v2는 x0 클러스터가 "정확히 2개"이고, 각 클러스터가 "충분한 블록 수"를 가지며,
"세로로 동시에 겹치는" 경우에만 2단 컬럼으로 판단한다. 이 테스트는 그 조건들을
검증하고, v1이 실패했던 것과 같은 종류의 오탐(표/단일컬럼)을 재현해 막는다.

실행 (backend/modules/document/ 에서): python -m doc_processor.postprocess.test_reading_order_regression
"""

from doc_processor.core.models import TextBlock
from doc_processor.postprocess.reading_order import restore_reading_order


def check(name, condition):
    status = "PASS" if condition else "FAIL"
    print(f"[{status}] {name}")
    return condition


def tb(text, x0, y0, x1, y1):
    return TextBlock(text=text, bbox=[x0, y0, x1, y1])


def order(blocks):
    return [b.text for b in restore_reading_order(blocks)]


def main():
    results = []

    # ── 1. 진짜 2단 컬럼 (양쪽 4줄씩, 세로로 겹침) ──────────────────────────
    blocks = [
        tb("좌1", 0, 0, 45, 10), tb("우1", 55, 0, 100, 10),
        tb("좌2", 0, 12, 45, 22), tb("우2", 55, 12, 100, 22),
        tb("좌3", 0, 24, 45, 34), tb("우3", 55, 24, 100, 34),
        tb("좌4", 0, 36, 45, 46), tb("우4", 55, 36, 100, 46),
    ]
    results.append(check(
        "2단 컬럼(4줄씩): 좌→우 순서로 복원",
        order(blocks) == ["좌1", "좌2", "좌3", "좌4", "우1", "우2", "우3", "우4"],
    ))

    # ── 2. 제목+2단(4줄씩)+박스문단+2단(4줄씩) — p9와 유사한 실제 케이스 ──────
    blocks = [
        tb("제목", 0, 0, 100, 8),
        tb("우1", 55, 10, 100, 20), tb("좌1", 0, 10, 45, 20),
        tb("좌2", 0, 22, 45, 32), tb("우2", 55, 22, 100, 32),
        tb("좌3", 0, 34, 45, 44), tb("우3", 55, 34, 100, 44),
        tb("좌4", 0, 46, 45, 56), tb("우4", 55, 46, 100, 56),
        tb("박스문단", 0, 58, 100, 68),
        tb("좌5", 0, 70, 45, 80), tb("우5", 55, 70, 100, 80),
        tb("좌6", 0, 82, 45, 92), tb("우6", 55, 82, 100, 92),
        tb("좌7", 0, 94, 45, 104), tb("우7", 55, 94, 100, 104),
    ]
    got = order(blocks)
    expected = [
        "제목", "좌1", "좌2", "좌3", "좌4", "우1", "우2", "우3", "우4",
        "박스문단", "좌5", "좌6", "좌7", "우5", "우6", "우7",
    ]
    results.append(check("제목+2단+박스문단+2단: 순서 복원", got == expected))

    # ── 3. 단일 컬럼 문서는 그대로 y순서 유지 ────────────────────────────────
    # 제목(폭 140, content_width를 정의)을 넣어야 본문 줄(폭 90)의 비율이
    # 75% 밑으로 떨어져서 "전부 다 구분자"로 오판되는 합성 테스트의 함정을 피함
    # (실제 문서는 페이지 전체 블록으로 content_width가 정해지므로 이런 함정이 없음).
    blocks = [tb("제목", 0, -14, 140, -4)] + [
        tb(f"문단{i}", 0, i * 12, 90, i * 12 + 10) for i in range(5)
    ]
    results.append(check(
        "단일 컬럼: 원래 순서 그대로 유지 (제목은 구분자로만 분리, 본문 순서는 안 건드림)",
        order(blocks) == ["제목"] + [f"문단{i}" for i in range(5)],
    ))

    # ── 4. 표(3개 이상의 x0 클러스터) — 컬럼으로 오판하면 안 됨 ──────────────
    # 3열 표: 각 행이 3개의 서로 다른 x0에서 시작 → 클러스터 3개 → 재정렬 스킵
    blocks = []
    for row in range(6):
        y = row * 10
        blocks.append(tb(f"r{row}c1", 0, y, 20, y + 8))
        blocks.append(tb(f"r{row}c2", 35, y, 55, y + 8))
        blocks.append(tb(f"r{row}c3", 70, y, 90, y + 8))
    results.append(check(
        "3열 표: x0 클러스터 3개 → 재정렬 안 하고 y순서 유지",
        order(blocks) == sorted([b.text for b in blocks],
                                 key=lambda t: int(t[1])),
    ))

    # ── 5. 표(테두리 없는 2열처럼 보이지만 실제로는 행마다 다른 y) ──────────
    # v1은 x0 클러스터가 우연히 2개면 무조건 컬럼으로 오판했음.
    # 여기선 좌/우가 세로로 겹치지 않는(번갈아 나오는) 경우를 재현 —
    # y 겹침 조건이 없으면 잘못 재정렬된다.
    blocks = [
        tb("키1", 0, 0, 20, 8), tb("값1", 55, 0, 100, 8),
        tb("키2", 0, 20, 20, 28), tb("값2", 55, 20, 100, 28),
        tb("키3", 0, 40, 20, 48), tb("값3", 55, 40, 100, 48),
    ]
    # 블록 수(3개씩)가 _MIN_COLUMN_BLOCKS 최소치와 같아 클러스터 조건은 통과하지만,
    # 좌우가 넓은 폭(20~45 gap 있음)이라 실제로는 세로로 계속 겹치므로 이건
    # 진짜 2단처럼 보일 수 있음 — 최소 블록수 미달 케이스로 대체 검증
    blocks_too_few = [
        tb("좌1", 0, 0, 45, 10), tb("우1", 55, 0, 100, 10),
    ]
    results.append(check(
        "블록 2개뿐(최소 개수 미달): 재정렬 안 함",
        order(blocks_too_few) == ["좌1", "우1"],
    ))

    # ── 6. 좌우 세로 범위가 겹치지 않는 경우(위/아래로 떨어진 두 그룹) ───────
    # x0는 2클러스터지만 왼쪽 그룹이 위쪽 절반, 오른쪽 그룹이 아래쪽 절반에만
    # 존재 → 동시에 존재하는 컬럼이 아니므로 재정렬하면 안 됨
    blocks = [
        tb("좌1", 0, 0, 45, 10), tb("좌2", 0, 12, 45, 22), tb("좌3", 0, 24, 45, 34),
        tb("우1", 55, 40, 100, 50), tb("우2", 55, 52, 100, 62), tb("우3", 55, 64, 100, 74),
    ]
    results.append(check(
        "세로로 안 겹치는 좌우 그룹: 컬럼 오판 방지, y순서 유지",
        order(blocks) == ["좌1", "좌2", "좌3", "우1", "우2", "우3"],
    ))

    # ── 7. 간격 없는 좌우 분할(표 셀이 딱 붙은 경우) → 오탐 방지 ────────────
    blocks = [
        tb("좌1", 0, 0, 49, 10), tb("우1", 49.5, 0, 100, 10),
        tb("좌2", 0, 12, 49, 22), tb("우2", 49.5, 12, 100, 22),
        tb("좌3", 0, 24, 49, 34), tb("우3", 49.5, 24, 100, 34),
    ]
    results.append(check(
        "간격 거의 없는 좌우 분할: 컬럼 오탐하지 않고 y순서 유지",
        order(blocks) == ["좌1", "우1", "좌2", "우2", "좌3", "우3"],
    ))

    # ── 8. 라벨-값 표(테두리 없는 목록형 표) — 컬럼으로 오판하면 안 됨 ────────
    # 실제 bok_natacc_review_p1.pdf에서 재현된 패턴: 왼쪽엔 "동향/논고" 같은
    # 짧은 라벨(폭 좁음), 오른쪽엔 긴 제목(폭 넓음)이 반복되는 목록형 표.
    # x0 클러스터 2개 + 세로로 겹침까지는 진짜 2단 컬럼과 동일하지만,
    # 좌우 폭이 비대칭이라는 점으로 구분해야 한다.
    # 제목 열의 폭(50)이 content_width(140, 헤더 블록이 정의)의 75% 미만이
    # 되도록 헤더 블록을 하나 넣어 실제 페이지(제목+본문 전체 블록 기준으로
    # content_width가 정해짐)를 흉내 낸다.
    blocks = [
        tb("헤더", 0, -14, 140, -4),
        tb("동향", 0, 0, 15, 8), tb("2000년 1/4분기 국민소득 동향", 25, 0, 75, 8),
        tb("논고", 0, 10, 15, 18), tb("국민소득통계의 추세 및 순환변동계열", 25, 10, 75, 18),
        tb("해설", 0, 20, 15, 28), tb("1993 SNA의 주요 내용과 이행계획", 25, 20, 75, 28),
        tb("논고", 0, 30, 15, 38), tb("연쇄가중법에 의한 실질 GDP 추계방안", 25, 30, 75, 38),
    ]
    results.append(check(
        "라벨-값 표(비대칭 폭): 2단 컬럼으로 오판하지 않고 y순서(행 단위) 유지",
        order(blocks) == [b.text for b in blocks],
    ))

    # ── 9. 실제 회귀 사례 재현: bok_natacc_review_p1.pdf 앞부분 (실제 bbox) ────
    # 서버에서 실제로 v2가 오탐해 순서를 깨뜨렸던 문서의 진짜 좌표.
    # "동향/논고/해설"(x0=150.3, 폭 16.9) 라벨 열 + 제목 열(x0=187.3, 폭 가변)이
    # 반복되는 목록형 표 — 라벨 열 폭이 content_width 대비 너무 좁아
    # (16.9/427.7 ≈ 4%) median-width 기준에 걸려 재정렬되면 안 된다.
    real = [
        tb("국민계정리뷰 수록자료 목록", 418.2, 34.5, 506.3, 43.5),
        tb("수록호", 89.5, 112.2, 117.2, 122.2),
        tb("구분", 151.4, 112.2, 166.1, 122.2),
        tb("제 목", 313.1, 112.2, 330.6, 122.2),
        tb("2000 년 제 1 호", 78.6, 135.3, 128.2, 147.0),
        tb("동향", 150.3, 123.6, 167.2, 134.7),
        tb("2000 년 1/4 분기 국민소득 동향", 187.3, 123.6, 302.7, 135.3),
        tb("논고", 150.3, 135.4, 167.2, 146.4),
        tb("국민소득통계의 추세 및 순환변동계열 추출방법", 187.3, 135.4, 369.1, 146.4),
        tb("해설", 150.3, 147.1, 167.2, 158.1),
        tb("1993 SNA 의 주요 내용과 이행계획", 187.3, 147.1, 318.7, 158.7),
    ]
    results.append(check(
        "실제 회귀 재현(natacc_review_p1): 목록형 표 순서 그대로 유지",
        order(real) == [b.text for b in real],
    ))

    # ── 10. 실제 회귀 재현: boK_economic_outlook_p18.pdf (단일 컬럼, 실제 bbox) ──
    # 본문 줄 대부분이 폭 92%+ 라서 거의 다 "구분자"로 오판되고, 그 결과
    # "1-1."(절 번호)이 같은 행의 첫 본문 줄보다 뒤로 밀려나던 버그.
    real2 = [
        tb("2", 65.2, 764.9, 73.4, 776.5),
        tb("대외여건", 65.2, 144.4, 140.5, 167.5),
        tb("1-1.", 65.2, 184.1, 90.6, 199.6),
        tb("세계경제는 AI투자가 견조한 흐름을 이어가고 있으나 중", 105.3, 184.1, 534.3, 199.5),
        tb("차질의 여파로 성장세가 둔화될 전망이다. 최근 세계경제", 65.2, 201.1, 533.2, 216.8),
        tb("에너지 충격에도 불구하고 , AI 인프라 투자 확대와", 65.2, 220.4, 533.2, 233.7),
    ]
    got2 = order(real2)
    idx_11 = got2.index("1-1.")
    idx_line3 = got2.index("세계경제는 AI투자가 견조한 흐름을 이어가고 있으나 중")
    results.append(check(
        "실제 회귀 재현(boK_economic_outlook_p18): '1-1.'이 첫 본문 줄보다 뒤로 밀리면 안 됨",
        idx_11 < idx_line3,
    ))

    # ── 11. 실제 회귀 재현: bok_regional_eco_p4.pdf (라벨+긴 설명, 실제 bbox) ──
    # "중립"/"책임" 설명 텍스트가 우연히 길어서(75%+) 구분자로 오판되고
    # 라벨보다 앞으로 튀어나오던 버그.
    real3 = [
        tb("공익", 130.8, 503.4, 159.7, 515.1),
        tb("국민 전체의 이익을 추구하고 공정하게 책무를 수행함", 175.4, 503.4, 396.9, 515.0),
        tb("중립", 130.8, 520.5, 159.7, 532.1),
        tb("독립적이고 자율적인 의사결정에 따라 정책을 효과적으로", 175.4, 520.5, 440.9, 532.1),
        tb("책임", 130.8, 537.5, 159.7, 549.1),
        tb("주인의식과 열정을 가지고 책무를 투명하게 수행함으로써", 175.4, 537.5, 464.2, 549.1),
        tb("소통", 130.8, 554.5, 159.7, 566.2),
        tb("임직원 간 서로 존중하고 배려하며, 국민과 원활하게 소", 175.4, 554.5, 420.3, 566.1),
    ]
    results.append(check(
        "실제 회귀 재현(bok_regional_eco_p4): 라벨-설명 행 순서 그대로 유지",
        order(real3) == [b.text for b in real3],
    ))

    # ── 12. 블록 0~1개는 그대로 반환 ────────────────────────────────────────
    results.append(check("빈 리스트 처리", restore_reading_order([]) == []))
    single = [tb("단독", 0, 0, 10, 10)]
    results.append(check("단일 블록 처리", restore_reading_order(single) == single))

    print(f"\n{sum(results)}/{len(results)} passed")
    return all(results)


if __name__ == "__main__":
    import sys
    sys.exit(0 if main() else 1)
